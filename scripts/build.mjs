import { readdirSync, rmSync, mkdirSync, cpSync, readFileSync, writeFileSync, lstatSync } from "fs";
import { execSync } from "child_process";
import { join, dirname, relative, extname, basename } from "path";

const ROOT = join(import.meta.dirname, "..");
const SKILLS_DIR = join(ROOT, "skills");
const OUTPUT_DIR = join(SKILLS_DIR, "upstash");

// Pre-check: ensure no unstaged changes under skills/upstash/
const diff = execSync("git diff --name-only -- skills/upstash/ claude-plugin/", { cwd: ROOT, encoding: "utf-8" }).trim();
if (diff) {
  console.error("\n >> Error: there are unstaged changes under skills/upstash/ or claude-plugin/. Stage or discard them before building.\n");
  console.error(diff);
  console.error();
  process.exit(1);
}

// Step 1: Remove existing upstash folder if it exists
rmSync(OUTPUT_DIR, { recursive: true, force: true });
mkdirSync(OUTPUT_DIR);

// Step 2: Get all skill folders (exclude upstash itself)
const skillFolders = readdirSync(SKILLS_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name !== "upstash")
  .map((d) => d.name)
  .sort();

const entries = [];

for (const folder of skillFolders) {
  const srcDir = join(SKILLS_DIR, folder);
  const destDir = join(OUTPUT_DIR, folder);

  // Step 3: Copy the skill folder into upstash/
  cpSync(srcDir, destDir, { recursive: true });

  // Step 4: Read SKILL.md, strip frontmatter, rename to overview.md
  const skillMdPath = join(destDir, "SKILL.md");
  const raw = readFileSync(skillMdPath, "utf-8");

  // Parse frontmatter
  const fmMatch = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  let description = "";
  let body = raw;

  if (fmMatch) {
    const frontmatter = fmMatch[1];
    body = fmMatch[2];

    const descMatch = frontmatter.match(/^description:\s*(.+)$/m);
    if (descMatch) {
      description = descMatch[1].trim();
    }
  }

  // Write overview.md (body without frontmatter)
  writeFileSync(join(destDir, "overview.md"), body.replace(/^\n+/, ""));
  rmSync(skillMdPath);

  entries.push({ folder, description });
}

// Claude rejects skills whose description is longer than 1024 characters.
const MAX_DESCRIPTION = 1024;
const headerDesc = readFileSync(join(import.meta.dirname, "header.md"), "utf-8").match(/^description:\s*(.+)$/m)?.[1].trim() ?? "";
const tooLong = [...entries, { folder: "upstash", description: headerDesc }].filter(
  ({ description }) => description.length > MAX_DESCRIPTION,
);
if (tooLong.length) {
  console.error(`\n >> Error: skill descriptions must be at most ${MAX_DESCRIPTION} characters.\n`);
  for (const { folder, description } of tooLong) console.error(`  ${folder}: ${description.length}`);
  console.error();
  process.exit(1);
}

// Step 5: Write the new SKILL.md using header template + generated entries
const header = readFileSync(join(import.meta.dirname, "header.md"), "utf-8");
const entryLines = entries
  .map(({ folder, description }) => `## [${folder}](${folder}/overview.md)\n\n${description}`)
  .join("\n\n");

writeFileSync(join(OUTPUT_DIR, "SKILL.md"), header + "\n" + entryLines + "\n");

console.log(`Built upstash skill with ${entries.length} sub-skills.`);

// Step 6: Build claude-plugin/, the folder submitted to the Claude plugin directory.
// The directory reads only the submitted folder, and from an unverified organization it
// accepts only Markdown, text, JSON, YAML and a few image types, with no symlinks, no
// files starting with #!, and no CLAUDE.md or AGENTS.md. The repo root holds build
// scripts, the Zed extension and AGENTS.md, so the plugin is shipped from a clean copy.
const PLUGIN_DIR = join(ROOT, "claude-plugin");
const claudeManifest = JSON.parse(readFileSync(join(ROOT, ".claude-plugin", "plugin.json"), "utf-8"));

rmSync(PLUGIN_DIR, { recursive: true, force: true });
mkdirSync(join(PLUGIN_DIR, ".claude-plugin"), { recursive: true });
writeFileSync(join(PLUGIN_DIR, ".claude-plugin", "plugin.json"), JSON.stringify(claudeManifest, null, 2) + "\n");
cpSync(SKILLS_DIR, join(PLUGIN_DIR, "skills"), { recursive: true });
const icon = join(PLUGIN_DIR, claudeManifest.icon);
mkdirSync(dirname(icon), { recursive: true });
cpSync(join(ROOT, claudeManifest.icon), icon);
cpSync(join(ROOT, "LICENSE"), join(PLUGIN_DIR, "LICENSE"));
writeFileSync(
  join(PLUGIN_DIR, "README.md"),
  "# Upstash Redis plugin for Claude\n\n" +
    "Generated by `npm run build` from the repository root. Do not edit this folder by hand.\n\n" +
    "This is the folder submitted to the Claude plugin directory: the Upstash MCP server plus the skills in `skills/`. " +
    "Install it in Claude Code with:\n\n" +
    "```\n/plugin install upstash --marketplace upstash/skills\n```\n\n" +
    "Sources: https://github.com/upstash/skills\n",
);

const ALLOWED = new Set([".md", ".txt", ".json", ".yaml", ".yml", ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico"]);
const refused = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    const rel = relative(PLUGIN_DIR, path);
    const stat = lstatSync(path);
    if (stat.isSymbolicLink()) refused.push(`${rel} (symbolic link)`);
    else if (stat.isDirectory()) walk(path);
    else if (/^(claude|claude\.local|agents)\.md$/i.test(basename(path))) refused.push(`${rel} (reserved name)`);
    else if (!ALLOWED.has(extname(path).toLowerCase()) && rel !== "LICENSE" && path !== icon) refused.push(`${rel} (file type)`);
    else if (readFileSync(path).subarray(0, 2).toString() === "#!") refused.push(`${rel} (starts with #!)`);
  }
};
walk(PLUGIN_DIR);
if (refused.length) {
  console.error("\n >> Error: the Claude plugin directory would refuse these files. Move them out of skills/ or convert them to Markdown.\n");
  for (const file of refused) console.error(`  claude-plugin/${file}`);
  console.error();
  process.exit(1);
}

console.log("Built claude-plugin/ for the Claude plugin directory.");
